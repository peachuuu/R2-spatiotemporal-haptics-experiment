static inline uint16_t lookupPulseWidth(const char* id, uint32_t elapsedUs, uint16_t fallback) {
  const PulseWidthLookupCurve* curve = pwCurveForSampleId(id);
  if (curve == NULL || curve->count == 0) return fallback;
  uint16_t value = curve->points[0].phaseWidthUs;
  for (uint16_t i = 1; i < curve->count && elapsedUs >= curve->points[i].atUs; ++i) value = curve->points[i].phaseWidthUs;
  return value;
}
